#!/usr/bin/env python3
"""Build the browser catalogue from the native launcher and show playlists."""

from __future__ import annotations

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent


def _playlist(path: pathlib.Path) -> list[str]:
    text = path.read_text(encoding="utf-8")
    return [name.upper() for name in re.findall(r"^\s*ENTRY\s+([a-z0-9]+),", text, re.MULTILINE)]


def _standalone_names() -> list[str]:
    launcher = (ROOT / "run-dosbox.sh").read_text(encoding="utf-8")
    match = re.search(r'^ORDER="([^"]+)"$', launcher, re.MULTILINE)
    if not match:
        raise ValueError("run-dosbox.sh has no ORDER catalogue")
    names = [name.upper() for name in match.group(1).split()]
    sources = {path.stem.upper() for path in (ROOT / "src").glob("*.asm")}
    if len(names) != len(set(names)) or set(names) != sources:
        raise ValueError("launcher ORDER and src/*.asm must contain the same unique demos")
    return names


def _family_names() -> list[str]:
    launcher = (ROOT / "run-dosbox.sh").read_text(encoding="utf-8")
    match = re.search(r'^FAMILY="([^"]+)"$', launcher, re.MULTILINE)
    if not match:
        raise ValueError("run-dosbox.sh has no FAMILY catalogue")
    names = [name.upper() for name in match.group(1).split()]
    expected = set(FAMILY_THUMBNAILS)
    if len(names) != len(set(names)) or set(names) != expected:
        raise ValueError("launcher FAMILY and family metadata must contain the same unique demos")
    return names


FAMILY_THUMBNAILS = {
    **{
        name: f"micro-{name.lower()}.jpg"
        for name in (
            "OVERLAP OVERMAX OVERSUB OVERHEAR STACKMAP STKRAIN BULLETS SNOW "
            "BREATH BUZZ STATIC TICKER GEIGER TYPER SPECTRUM STRIPE BIG TALL "
            "KEYSCAN PSPBACK STATE FLUX WEAVE CODEPAL PSPPAL NOISEPAL MODE3 EVO1 EVO2"
        ).split()
    },
    "MIRROR8": "micro-mirror.jpg",
    "UBER10": "uber10.jpg",
    "UBER128": "uber128.jpg",
}


def _thumbnail(name: str) -> str:
    if name in FAMILY_THUMBNAILS:
        return FAMILY_THUMBNAILS[name]
    stem = name.lower()
    candidates = (
        f"{stem}-atlas.png",
        f"{stem}.jpg",
        f"{stem}-a.jpg",
        f"{stem}-early.jpg",
        f"{stem}.gif",
    )
    for candidate in candidates:
        if (ROOT / "docs" / candidate).is_file():
            return candidate
    raise ValueError(f"{name} has no screenshot thumbnail in docs/")


def _size(name: str) -> int:
    path = ROOT / f"{name}.COM"
    if not path.is_file():
        raise ValueError(f"{path.name} is missing; run ./build.sh before generating the web catalogue")
    return path.stat().st_size


def build_catalog() -> dict[str, object]:
    standalone = [[name, _thumbnail(name), _size(name)] for name in [*_standalone_names(), *_family_names()]]
    by_name = {name: [image, size] for name, image, size in standalone}
    mega = _playlist(ROOT / "src" / "mega" / "mega_program.inc")
    atlas = _playlist(ROOT / "src" / "mega" / "atlas_program.inc")
    return {
        "standalone": standalone,
        "shows": {
            "MEGA": [[name, *by_name[name]] for name in mega],
            "ATLAS": [[name, *by_name[name]] for name in atlas],
            "UBERSHOW": [["UBERSHOW", "ubershow.jpg", _size("UBERSHOW")]],
            "UBER70": [["UBER70", "ubershow.jpg", _size("UBER70")]],
            "UBER40K": [["UBER40K", "uber40k.jpg", _size("UBER40K")]],
        },
    }


def load_catalog(path: pathlib.Path) -> dict[str, object]:
    text = path.read_text(encoding="utf-8")
    prefix = "window.UBER256_CATALOG="
    if not text.startswith("// Generated by tools/build_web_catalog.py; do not edit.\n" + prefix) or not text.rstrip().endswith(";"):
        raise ValueError(f"invalid generated catalogue: {path}")
    return json.loads(text[text.index(prefix) + len(prefix):].rstrip()[:-1])


def javascript() -> str:
    return (
        "// Generated by tools/build_web_catalog.py; do not edit.\n"
        "window.UBER256_CATALOG="
        + json.dumps(build_catalog(), separators=(",", ":"))
        + ";\n"
    )
